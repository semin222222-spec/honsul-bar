/**
 * 카테고리 + 단어 랜덤 선택. '랜덤'을 주면 카테고리도 무작위.
 *
 * @param {string} category
 * @returns {{ category: string, word: string }}
 */
export function pickRandomWord(category) {
  let cat = category;
  if (!cat || cat === "랜덤" || !LIAR_WORDS[cat]) {
    const keys = Object.keys(LIAR_WORDS);
    cat = keys[Math.floor(Math.random() * keys.length)];
  }
  const words = LIAR_WORDS[cat];
  const word = words[Math.floor(Math.random() * words.length)];
  return { category: cat, word };
}
