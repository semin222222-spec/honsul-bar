/**
 * 매운맛에 맞는 질문 풀 반환.
 * @param {('mild'|'medium')} spice
 * @returns {string[]}
 */
export function getQuestionPool(spice) {
  return spice === "mild" ? MILD_QUESTIONS : MEDIUM_QUESTIONS;
}

/**
 * 매운맛 풀에서 이미 보여준 질문을 제외하고 랜덤 1개.
 * 모두 소진했으면 전체 풀에서 다시 뽑는다.
 *
 * @param {('mild'|'medium')} spice
 * @param {string[]} usedQuestions
 * @returns {string}
 */
export function pickRandomQuestion(spice, usedQuestions = []) {
  const pool = getQuestionPool(spice);
  const used = new Set(usedQuestions);
  const remaining = pool.filter((q) => !used.has(q));
  const from = remaining.length > 0 ? remaining : pool;
  return from[Math.floor(Math.random() * from.length)];
}
