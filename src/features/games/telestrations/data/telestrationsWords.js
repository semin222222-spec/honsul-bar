// 중복 제거 + 동결
export const TELESTRATIONS_WORDS = Object.freeze([
  ...new Set(WORDS_RAW),
]);

/**
 * 단어 풀에서 count 개를 중복 없이 무작위로 뽑음.
 * count 가 풀 크기보다 크면 풀 전체를 셔플해서 반환.
 */
export function pickRandomWords(count) {
  const n = Math.max(0, Math.min(count, TELESTRATIONS_WORDS.length));
  if (n === 0) return [];
  const pool = [...TELESTRATIONS_WORDS];
  // Fisher-Yates shuffle (n 개만 채워도 충분)
  for (let i = 0; i < n; i++) {
    const j = i + Math.floor(Math.random() * (pool.length - i));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, n);
}
