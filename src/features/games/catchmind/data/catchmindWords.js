export const CATCHMIND_CATEGORIES = {
  animal: { label: "동물", words: ANIMAL },
  object: { label: "사물", words: OBJECT },
  food: { label: "음식", words: FOOD },
  movie: { label: "영화·인물", words: MOVIE },
  job: { label: "직업", words: JOB },
  action: { label: "행동·감정", words: ACTION },
};

export const ALL_CATCHMIND_WORDS = [
  ...ANIMAL,
  ...OBJECT,
  ...FOOD,
  ...MOVIE,
  ...JOB,
  ...ACTION,
];

/**
 * 단어 풀에서 사용한 단어를 제외하고 랜덤 단어 선택.
 * @param {string[]} usedWords 이전 라운드에서 이미 사용한 단어들
 * @returns {{word: string, category: string}}
 */
export function pickRandomWord(usedWords = []) {
  const used = new Set(usedWords);
  const pool = ALL_CATCHMIND_WORDS.filter((w) => !used.has(w));
  // 풀이 비면 (이론상 불가능) 전체에서 다시
  const source = pool.length > 0 ? pool : ALL_CATCHMIND_WORDS;
  const word = source[Math.floor(Math.random() * source.length)];
  let category = "etc";
  for (const [key, val] of Object.entries(CATCHMIND_CATEGORIES)) {
    if (val.words.includes(word)) {
      category = key;
      break;
    }
  }
  return { word, category };
}
